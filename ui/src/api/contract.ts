import {
  dereference,
  validate,
  type OutputUnit,
  type Schema,
} from "@cfworker/json-schema";

import eventSchemas from "./generated/event-schemas.json" with { type: "json" };
import publicSchemas from "./generated/public-schemas.json" with { type: "json" };
import {
  EVENT_SCHEMA_ID,
  PUBLIC_SCHEMA_ID,
  REQUEST_HEADER_SCHEMAS,
  RESPONSE_SCHEMAS,
  type EventSchemaName,
  type PublicSchemaName,
  type ResponseOperation,
} from "./generated/response-schemas";

export type { ResponseOperation };

/**
 * The run-time view of the pinned public contract: the OpenAPI component
 * schemas and the event frame schema, generated by scripts/generate-schemas.mjs
 * and interpreted by @cfworker/json-schema (no eval, which the UI
 * Content-Security-Policy forbids). Every rule the UI shares with the Server
 * (identifier grammars, limits, enums) is read from here rather than copied.
 */

const MAXIMUM_LOCATION = 200;

let lookup: Record<string, Schema | boolean> | undefined;
const references = new Map<string, Schema>();

function schemas(): Record<string, Schema | boolean> {
  // Dereferencing indexes every subschema once (about 9 ms); it runs on the
  // first validation rather than at module load.
  if (lookup === undefined) {
    const next = dereference(publicSchemas as Schema);
    dereference(eventSchemas as Schema, next);
    lookup = next;
  }
  return lookup;
}

function reference(uri: string): Schema {
  let schema = references.get(uri);
  if (schema === undefined) {
    schema = { $ref: uri };
    references.set(uri, schema);
  }
  return schema;
}

function publicURI(name: PublicSchemaName): string {
  return `${PUBLIC_SCHEMA_ID}#/$defs/${name}`;
}

/** The most specific failing instance location, without any value. */
function location(errors: readonly OutputUnit[]): string {
  let deepest = "#";
  for (const error of errors) {
    if (error.instanceLocation.length > deepest.length) {
      deepest = error.instanceLocation;
    }
  }
  return deepest.length > MAXIMUM_LOCATION
    ? `${deepest.slice(0, MAXIMUM_LOCATION)}…`
    : deepest;
}

/** The first failing location of `value` under the schema at `uri`. */
function violation(value: unknown, uri: string): string | undefined {
  if (value === undefined) return "#";
  const result = validate(value, reference(uri), "2020-12", schemas(), true);
  return result.valid ? undefined : location(result.errors);
}

/** Where `value` breaks the named public component schema, if it does. */
export function schemaViolation(
  name: PublicSchemaName,
  value: unknown,
): string | undefined {
  return violation(value, publicURI(name));
}

/** Whether `value` conforms to the named public component schema. */
export function conformsTo(name: PublicSchemaName, value: unknown): boolean {
  return schemaViolation(name, value) === undefined;
}

/**
 * Why a response body breaks the operation's declared response, or undefined
 * when it conforms. `body` is undefined for a response without content.
 */
export function responseViolation(
  operation: ResponseOperation,
  status: number,
  body: unknown,
): string | undefined {
  const declared: Readonly<Record<string, PublicSchemaName | null>> =
    RESPONSE_SCHEMAS[operation];
  const name = declared[String(status)];
  if (name === undefined) return `status ${status} is not declared`;
  if (name === null) {
    return body === undefined ? undefined : "an undeclared body was returned";
  }
  const at = violation(body, publicURI(name));
  return at === undefined ? undefined : `the body does not conform at ${at}`;
}

/**
 * Why a request header value breaks the schema `operation` declares for it,
 * if it does. Headers the operation does not declare are not checked here.
 */
export function requestHeaderViolation(
  operation: ResponseOperation,
  header: string,
  value: unknown,
): string | undefined {
  const declared: Readonly<Record<string, PublicSchemaName>> | undefined = (
    REQUEST_HEADER_SCHEMAS as Partial<
      Record<ResponseOperation, Readonly<Record<string, PublicSchemaName>>>
    >
  )[operation];
  const name = declared?.[header];
  return name === undefined ? undefined : violation(value, publicURI(name));
}

/** Why a parsed event frame breaks contractor-events-v1, if it does. */
export function eventFrameViolation(frame: unknown): string | undefined {
  return violation(frame, EVENT_SCHEMA_ID);
}

/** Whether `value` conforms to the named contractor-events-v1 schema. */
export function conformsToEvent(
  name: EventSchemaName,
  value: unknown,
): boolean {
  return violation(value, `${EVENT_SCHEMA_ID}#/$defs/${name}`) === undefined;
}

/** Whether `method` and `path` name an operation with declared responses. */
export function isResponseOperation(key: string): key is ResponseOperation {
  return Object.hasOwn(RESPONSE_SCHEMAS, key);
}

type SchemaObject = Record<string, unknown>;

function schemaAt(
  name: PublicSchemaName,
  path: readonly string[],
): SchemaObject {
  let value: unknown = (publicSchemas.$defs as Record<string, unknown>)[name];
  for (const key of path) {
    value =
      typeof value === "object" && value !== null
        ? (value as Record<string, unknown>)[key]
        : undefined;
  }
  if (typeof value !== "object" || value === null || Array.isArray(value)) {
    throw new Error(
      `Public contract has no schema at ${name}/${path.join("/")}`,
    );
  }
  return value as SchemaObject;
}

function numberKeyword(
  schema: SchemaObject,
  keyword: string,
): number | undefined {
  const value = schema[keyword];
  return typeof value === "number" ? value : undefined;
}

/** A string schema's checks, for forms that validate before sending. */
interface StringRule {
  readonly minLength?: number;
  readonly maxLength?: number;
  /** UTF-8 byte bounds (the x-min/max-utf8-bytes extensions). */
  readonly minBytes?: number;
  readonly maxBytes?: number;
  readonly pattern?: RegExp;
  /** Whether `value` satisfies every check, as the Server validates it. */
  test(value: string): boolean;
}

const encoder = new TextEncoder();

/**
 * The checks of the string schema at `name` (or at `path` inside it, for
 * example ["properties", "scheme"]). Lengths count Unicode code points, as
 * JSON Schema does.
 */
export function stringRule(
  name: PublicSchemaName,
  ...path: string[]
): StringRule {
  const schema = schemaAt(name, path);
  if (schema.type !== "string") {
    throw new Error(`Public contract ${name} is not a string schema`);
  }
  const minLength = numberKeyword(schema, "minLength");
  const maxLength = numberKeyword(schema, "maxLength");
  const minBytes = numberKeyword(schema, "x-min-utf8-bytes");
  const maxBytes = numberKeyword(schema, "x-max-utf8-bytes");
  const pattern =
    typeof schema.pattern === "string"
      ? new RegExp(schema.pattern, "u")
      : undefined;
  return {
    ...(minLength === undefined ? {} : { minLength }),
    ...(maxLength === undefined ? {} : { maxLength }),
    ...(minBytes === undefined ? {} : { minBytes }),
    ...(maxBytes === undefined ? {} : { maxBytes }),
    ...(pattern === undefined ? {} : { pattern }),
    test(value: string): boolean {
      const length = [...value].length;
      if (minLength !== undefined && length < minLength) return false;
      if (maxLength !== undefined && length > maxLength) return false;
      if (minBytes !== undefined || maxBytes !== undefined) {
        const bytes = encoder.encode(value).length;
        if (minBytes !== undefined && bytes < minBytes) return false;
        if (maxBytes !== undefined && bytes > maxBytes) return false;
      }
      return pattern === undefined || pattern.test(value);
    },
  };
}

/** The `enum` of the schema at `name` (or at `path` inside it). */
export function schemaEnum<T extends string = string>(
  name: PublicSchemaName,
  ...path: string[]
): readonly T[] {
  const values = schemaAt(name, path).enum;
  if (
    !Array.isArray(values) ||
    values.some((value) => typeof value !== "string")
  ) {
    throw new Error(`Public contract ${name} has no string enum`);
  }
  return Object.freeze([...(values as T[])]);
}

/** A numeric keyword (maximum, maxItems, ...) of the schema at `name`. */
export function schemaLimit(
  name: PublicSchemaName,
  keyword:
    | "minimum"
    | "maximum"
    | "exclusiveMinimum"
    | "exclusiveMaximum"
    | "minItems"
    | "maxItems"
    | "minLength"
    | "maxLength"
    | "minProperties"
    | "maxProperties",
  ...path: string[]
): number {
  const value = numberKeyword(schemaAt(name, path), keyword);
  if (value === undefined) {
    throw new Error(`Public contract ${name} has no ${keyword}`);
  }
  return value;
}

/*
 * Shared rules: the public grammars the UI checks before it sends a value
 * (route parameters, If-Match revisions, form fields). Each one is the
 * generated schema itself, so it cannot drift from the Server.
 */

