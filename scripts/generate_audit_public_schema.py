#!/usr/bin/env python3
"""Project the owning common Audit Program schema into the public OpenAPI file."""

import argparse
import json
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "api/openapi/contractor-public-v1.yaml"
START = "    # BEGIN GENERATED COMMON AUDIT PROGRAM\n"
END = "    # END GENERATED COMMON AUDIT PROGRAM\n"
NAMES = {
    "finding_check": "FindingCheck",
    "task_stop": "AuditTaskStop", "result_stop": "AuditResultStop",
    "parameter": "AuditProgramParameter",
    "program": "AuditProgram", "input": "AuditProgramInput", "limits": "AuditProgramLimits",
    "workflow": "AuditProgramWorkflow", "input_mapping": "AuditProgramInputMapping",
    "seed": "AuditProgramHypothesisSeed", "initial": "AuditProgramInitialWork",
    "attempt_limit": "AuditProgramAttemptLimit",
 "seed_source": "AuditProgramSeedSource",
 "assertion_source": "AuditAssertionsSource", "assertion_source_entry": "AuditAssertionSourceEntry",
 "hypothesis": "AuditHypothesisDocument", "assertion_scope": "AuditAssertionScope", "artifact": "AuditTaskMaterial",
    "key": "AuditCommonKey", "text": "AuditCommonText", "digest": "AuditCommonDigest",
    "resource_id": "AuditCommonResourceId", "ref": "AuditCommonExactRef",
}
SHARED = {"key", "text", "digest", "resource_id", "ref"}


def generated():
    schema = json.loads((ROOT / "api/audit/v1/contract.schema.json").read_text())
    common=json.loads((ROOT / "api/v1alpha1/common.schema.json").read_text())
    material=json.loads((ROOT / "api/v1alpha1/material-set.schema.json").read_text())
    selected = {}

    def copy(value, owner="audit"):
        if isinstance(value, list):
            return [copy(item, owner) for item in value]
        if not isinstance(value, dict):
            return value
        result = {}
        for key, child in value.items():
            if key == "$ref":
                if "material-set.schema.json" in child or owner == "material" and child.startswith("#/"):
                    name=child.rsplit("/",1)[-1]
                    target="WorkflowMaterialDescriptor"
                    if target not in selected:
                        selected[target]=None
                        selected[target]=copy(material["$defs"][name], "material")
                elif child.startswith("#/$defs/"):
                    name = child.removeprefix("#/$defs/")
                    target = NAMES[name]
                    if name not in SHARED and target not in selected:
                        selected[target] = None
                        selected[target] = copy(schema["$defs"][name])
                else:
                    if "common.schema.json#/$defs/" not in child:
                        raise ValueError("unexpected external Program schema reference")
                    name=child.rsplit("/",1)[-1]
                    target={"name":"AuditCommonKey","mediaType":"MediaType","selector":"AuditProgramSelector", "version":"ConfigVersion", "opaqueId":"AuditMaterialScopeId", "exactArtifactRef":"AuditCommonExactRef", "digest":"AuditCommonDigest"}[name]
                    if name in {"selector", "opaqueId"}:selected[target]=copy(common["$defs"][name])
                child = "#/components/schemas/" + target
            result[key] = copy(child, owner)
        # Public schemas spell out scalar types for strict client validators.
        values = [result["const"]] if "const" in result else result.get("enum", [])
        if values and "type" not in result and all(isinstance(v, str) for v in values):
            result["type"] = "string"
        return result

    copy({"$ref": "#/$defs/program"})
    copy({"$ref": "#/$defs/hypothesis"})
    copy({"$ref": "#/$defs/assertion_source"})
    copy({"$ref": "#/$defs/task_stop"})
    copy({"$ref": "#/$defs/finding_check"})
    selected["AuditProgramPolicy"] = copy(schema["$defs"]["program"]["properties"]["policy"])
    selected["AuditProgram"]["properties"]["policy"] = {"$ref": "#/components/schemas/AuditProgramPolicy"}
    body = yaml.safe_dump(selected, sort_keys=True, allow_unicode=True, width=100)
    return START + "    # Generated by scripts/generate_audit_public_schema.py; do not edit.\n" + "".join(
        "    " + line + "\n" for line in body.splitlines()
    ) + END


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    original = OUTPUT.read_text()
    start, end = original.index(START), original.index(END) + len(END)
    desired = original[:start] + generated() + original[end:]
    if args.check:
        if original != desired:
            parser.error("public Audit Program schema drift; run scripts/generate_audit_public_schema.py")
    else:
        OUTPUT.write_text(desired)


if __name__ == "__main__":
    main()
