"""Compile deployment model selection into ModelPolicies and LiteLLM routes.

Run through make model-config / model-config-check (Runtime's locked PyYAML).
This is an offline authoring tool; the Server and Runtime consume only the
existing generated contracts. No credentials or provider discovery are read.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import math
import os
import re
import stat
import sys
import tempfile
from pathlib import Path
from urllib.parse import urlsplit

import yaml

ROOT = Path(__file__).resolve().parent.parent
ROLES = ("planner", "worker", "summarizer", "audit_completion_worker")
MAX_BYTES = 65536
MAX_PROFILES = 32
MAX_OUTPUT_BYTES = 1024 * 1024
HEADER = "# Generated by make model-config; edit deploy/models/ instead.\n"
BUDGET_LIMITS = {
    "maxOutputTokens": 100_000_000,
    "maxModelCalls": 1000,
    "maxToolCalls": 10000,
    "maxWorkerCalls": 10000,
    "maxTotalTokens": 100_000_000,
}


class ConfigError(ValueError):
    """Invalid deployment input or an unsafe generation target."""


class UniqueLoader(yaml.SafeLoader):
    def construct_mapping(self, node, deep=False):
        result = {}
        for key_node, value_node in node.value:
            key = self.construct_object(key_node, deep=deep)
            if not isinstance(key, str) or key in result:
                raise ConfigError("mapping keys must be unique strings")
            result[key] = self.construct_object(value_node, deep=deep)
        return result


def safe_path(root: Path, relative: str) -> Path:
    path = root / relative
    for part in (path, *path.parents):
        if part == root:
            break
        if part.is_symlink():
            raise ConfigError(f"{relative}: symlinks are not allowed")
        if part.exists() and part != path and not part.is_dir():
            raise ConfigError(f"{relative}: parent is not a directory")
    if path.exists() and not stat.S_ISREG(path.stat().st_mode):
        raise ConfigError(f"{relative}: expected a regular file")
    return path


def load(root: Path, relative: str) -> dict:
    path = safe_path(root, relative)
    with path.open("rb") as source:
        data = source.read(MAX_BYTES + 1)
    if len(data) > MAX_BYTES:
        raise ConfigError(f"{relative}: exceeds {MAX_BYTES} bytes")
    try:
        # Aliases/anchors and merge keys add needless indirection and can expand
        # unbounded structures; deployment sources are small, literal mappings.
        if any(isinstance(token, (yaml.AliasToken, yaml.AnchorToken)) for token in yaml.scan(data)):
            raise ConfigError("YAML anchors and aliases are not allowed")
        value = yaml.load(data, Loader=UniqueLoader)
    except (yaml.YAMLError, UnicodeError, ConfigError) as error:
        # Do not echo source values: a mistaken credential must not enter logs.
        raise ConfigError(f"{relative}: invalid literal YAML mapping") from error
    if not isinstance(value, dict):
        raise ConfigError(f"{relative}: expected a mapping")
    return value


def fields(value: dict, required: set, optional: set = frozenset()) -> None:
    if not required <= value.keys() or value.keys() - required - optional:
        raise ConfigError("missing or unknown fields")


def text_value(value, pattern: str, label: str, maximum: int = 160) -> str:
    if not isinstance(value, str) or len(value) > maximum or not re.fullmatch(pattern, value):
        raise ConfigError(f"invalid {label}")
    return value


def positive(value, maximum: int, label: str) -> int:
    if type(value) is not int or not 0 < value <= maximum:
        raise ConfigError(f"{label} must be a positive integer at most {maximum}")
    return value


def profile(value: dict) -> dict:
    fields(value, {"model", "apiBase", "apiKeyEnv", "contextWindowTokens", "maxOutputTokens"})
    text_value(value["model"], r"[a-z][a-z0-9_-]*/[A-Za-z0-9_.:/-]+", "upstream model")
    text_value(value["apiKeyEnv"], r"[A-Z][A-Z0-9_]*", "API-key environment name", 80)
    base = value["apiBase"]
    if not isinstance(base, str) or len(base) > 256:
        raise ConfigError("invalid API base")
    parsed = urlsplit(base)
    if (
        parsed.scheme != "https"
        or not parsed.hostname
        or parsed.username is not None
        or parsed.password is not None
        or parsed.query
        or parsed.fragment
        or any(character.isspace() for character in base)
    ):
        raise ConfigError("API base must be HTTPS without credentials, query or fragment")
    positive(value["contextWindowTokens"], 100_000_000, "contextWindowTokens")
    positive(value["maxOutputTokens"], 100_000_000, "model maxOutputTokens")
    if value["maxOutputTokens"] >= value["contextWindowTokens"]:
        raise ConfigError("model output capacity must be smaller than its context")
    return value


def role_budget(role: str, value: dict) -> dict:
    if not isinstance(value, dict):
        raise ConfigError(f"{role}: expected role mapping")
    required = {"policyVersion", "gatewayAlias", "maxOutputTokens", "maxModelCalls"}
    if role != "summarizer":
        required.add("maxTotalTokens")
        required.add("maxWorkerCalls" if role == "planner" else "maxToolCalls")
    fields(value, required, {"temperature", "maxTotalTokens"})
    text_value(value["policyVersion"], r"[A-Za-z0-9][A-Za-z0-9._+-]*", "policy version", 64)
    text_value(value["gatewayAlias"], r"[A-Za-z0-9][A-Za-z0-9._-]*", "Gateway alias")
    for key, maximum in BUDGET_LIMITS.items():
        if key in value:
            positive(value[key], maximum, key)
    if role == "summarizer" and value["maxModelCalls"] != 1:
        raise ConfigError("summarizer must permit exactly one model call")
    if "temperature" in value:
        temperature = value["temperature"]
        if (
            type(temperature) not in (int, float)
            or not math.isfinite(temperature)
            or temperature < 0
        ):
            raise ConfigError("temperature must be finite and nonnegative")
    return value


def encode(value: dict) -> bytes:
    return (HEADER + yaml.safe_dump(value, sort_keys=False, allow_unicode=True)).encode("utf-8")


def render(root: Path) -> dict[str, bytes]:
    selection = load(root, "deploy/models/selection.yaml")
    fields(selection, {"defaultModel", "roles"})
    selected = selection["roles"]
    if not isinstance(selected, dict) or selected.keys() - set(ROLES):
        raise ConfigError("selection roles must name only the four supported roles")
    budgets = load(root, "deploy/models/roles.yaml")
    fields(budgets, set(ROLES))
    catalog = root / "deploy/models/catalog"
    if catalog.is_symlink() or not catalog.is_dir():
        raise ConfigError("model catalog must be a regular directory")
    models = {}
    # Stop enumeration at the bound, rather than collecting a large directory.
    for path in catalog.iterdir():
        if len(models) >= MAX_PROFILES:
            raise ConfigError(f"model catalog exceeds {MAX_PROFILES} profiles")
        text_value(path.name, r"[a-z0-9][a-z0-9.-]*\.yaml", "model profile filename", 80)
        models[path.stem] = profile(load(root, str(path.relative_to(root))))
    default = selection["defaultModel"]
    if not isinstance(default, str) or default not in models:
        raise ConfigError("defaultModel must select an existing profile")
    output = {}
    routes = []
    choices = []
    compiled = {}
    validated_budgets = {role: role_budget(role, budgets[role]) for role in ROLES}
    if len({budget["gatewayAlias"] for budget in validated_budgets.values()}) != len(ROLES):
        raise ConfigError("role Gateway aliases must be distinct")
    for model_id in sorted(models):
        model = models[model_id]
        digest = hashlib.sha256(
            json.dumps({"id": model_id, **model}, sort_keys=True, separators=(",", ":")).encode()
        ).hexdigest()
        policies = {}
        for role in ROLES:
            budget = validated_budgets[role]
            if (
                budget["maxOutputTokens"] > model["maxOutputTokens"]
                or budget["maxOutputTokens"] >= model["contextWindowTokens"]
            ):
                continue
            # The model identifier and profile digest travel with every request
            # and Run snapshot. A selection change never retargets an old alias.
            alias = f"{model['model']}@{digest[:16]}/{budget['gatewayAlias']}"
            name = f"{role}_{model_id.replace('.', '_').replace('-', '_')[:32]}_{digest[:16]}"
            spec = {"model": alias, "contextWindowTokens": model["contextWindowTokens"]}
            spec.update(
                {key: budget[key] for key in (*BUDGET_LIMITS, "temperature") if key in budget}
            )
            document = {
                "apiVersion": "contractor/v1alpha1",
                "kind": "ModelPolicy",
                "metadata": {"name": name, "version": budget["policyVersion"]},
                "spec": spec,
            }
            output[f"configs/model-policies/models/{name}.yaml"] = encode(document)
            compiled[model_id, role] = document
            policies[role] = f"{name}@{budget['policyVersion']}"
            routes.append(
                {
                    "model_name": alias,
                    "litellm_params": {
                        "model": model["model"],
                        "api_base": model["apiBase"],
                        "api_key": f"os.environ/{model['apiKeyEnv']}",
                        "timeout": 240,
                    },
                }
            )
        if not policies:
            raise ConfigError(f"{model_id}: model cannot fit any role's output budget")
        choices.append(
            {
                "id": model_id,
                "digest": f"sha256:{digest}",
                "upstreamModel": model["model"],
                "contextWindowTokens": model["contextWindowTokens"],
                "maxOutputTokens": model["maxOutputTokens"],
                "policies": policies,
            }
        )
    for role in ROLES:
        model_id = selected.get(role, default)
        if not isinstance(model_id, str) or model_id not in models:
            raise ConfigError(f"{role}: must select an existing model profile")
        if (model_id, role) not in compiled:
            raise ConfigError(
                f"{role}: output limit exceeds selected model output capacity or context"
            )
        document = dict(compiled[model_id, role])
        document["metadata"] = {"name": role, "version": validated_budgets[role]["policyVersion"]}
        output[f"configs/model-policies/{role}.yaml"] = encode(document)
    output["deploy/litellm/litellm_config.yaml"] = encode(
        {
            "model_list": routes,
            "litellm_settings": {"num_retries": 0, "request_timeout": 240, "set_verbose": False},
        }
    )
    output["configs/model-selection.json"] = (
        json.dumps(
            {
                "schemaVersion": "1",
                "initialSelection": selection,
                "models": choices,
            },
            indent=2,
            ensure_ascii=False,
        )
        + "\n"
    ).encode()
    if any(len(data) > MAX_OUTPUT_BYTES for data in output.values()):
        raise ConfigError("generated output exceeds 1 MiB")
    return output


def generate(root: Path, check: bool = False) -> list[str]:
    output = render(root)
    # Preflight every target before any replacement. Each file is replaced
    # atomically; interrupted multi-file generation is detected by --check.
    targets = {name: safe_path(root, name) for name in output}
    obsolete = []
    model_directory = root / "configs/model-policies/models"
    if model_directory.exists():
        for index, path in enumerate(model_directory.iterdir()):
            if index >= MAX_PROFILES * len(ROLES) * 2:
                raise ConfigError("generated model policy directory exceeds recovery bound")
            name = str(path.relative_to(root))
            safe_path(root, name)
            if name in output:
                continue
            with path.open("rb") as current:
                if not current.read(MAX_OUTPUT_BYTES + 1).startswith(HEADER.encode()):
                    raise ConfigError("unexpected file in generated model policy directory")
            obsolete.append(name)
    changed = []
    for name, path in targets.items():
        if not path.exists():
            changed.append(name)
            continue
        with path.open("rb") as current:
            if current.read(MAX_OUTPUT_BYTES + 1) != output[name]:
                changed.append(name)
    if not check:
        for name in changed:
            path = targets[name]
            path.parent.mkdir(parents=True, exist_ok=True)
            temporary = None
            try:
                with tempfile.NamedTemporaryFile(dir=path.parent, delete=False) as target:
                    temporary = Path(target.name)
                    target.write(output[name])
                temporary.chmod(0o644)
                os.replace(temporary, path)
            finally:
                if temporary is not None:
                    temporary.unlink(missing_ok=True)
        for name in obsolete:
            (root / name).unlink()
    return changed + sorted(obsolete)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=ROOT)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    try:
        changed = generate(args.root.resolve(), args.check)
    except (ConfigError, OSError, ValueError, RecursionError) as error:
        # OSError messages name paths, never source values.
        print(f"model configuration failed: {error}", file=sys.stderr)
        return 1
    if args.check and changed:
        print("generated model configuration is stale; run make model-config", file=sys.stderr)
        for name in changed:
            print(f"  {name}", file=sys.stderr)
        return 1
    print(f"model configuration {'checked' if args.check else 'generated'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
