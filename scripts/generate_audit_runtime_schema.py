#!/usr/bin/env python3
"""Copy ordinary Audit completion and retained hypothesis contracts into Runtime."""

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "runtime/src/contractor_runtime/contracts/audit_documents.schema.json"


def generated():
    audit = json.loads((ROOT / "api/audit/v1/contract.schema.json").read_text())
    common = json.loads((ROOT / "api/v1alpha1/common.schema.json").read_text())
    material = json.loads((ROOT / "api/v1alpha1/material-set.schema.json").read_text())
    owners = {"audit": audit, "common": common, "material": material}
    selected = {}

    def copy(value, owner="audit"):
        if isinstance(value, list):
            return [copy(item, owner) for item in value]
        if not isinstance(value, dict):
            return value
        result = {}
        for key, child in value.items():
            if key == "$ref":
                name = child.rsplit("/", 1)[-1]
                target_owner = owner
                if not child.startswith("#/"):
                    target_owner = "material" if "material-set.schema.json" in child else "common"
                identity = ("" if target_owner == "audit" else target_owner + "_") + name
                if identity not in selected:
                    selected[identity] = None
                    selected[identity] = copy(owners[target_owner]["$defs"][name], target_owner)
                child = "#/$defs/" + identity
            result[key] = copy(child, owner)
        return result

    roots = [copy({"$ref": "#/$defs/" + name}) for name in ("context", "conclusions", "hypothesis", "proposal_context", "proposals", "program")]
    return json.dumps({
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "$comment": "Generated by scripts/generate_audit_runtime_schema.py; do not edit.",
        "oneOf": roots,
        "$defs": selected,
    }, ensure_ascii=False, sort_keys=True, indent=2) + "\n"


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    content = generated()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != content:
            parser.error("Audit Runtime schema differs; run scripts/generate_audit_runtime_schema.py")
    else:
        OUTPUT.write_text(content)


if __name__ == "__main__":
    main()
