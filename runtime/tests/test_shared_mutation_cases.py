"""The generated wire mutations: the schema, Go and the Runtime reject each one.

api/testdata/v1alpha1/mutation-cases.json is generated by the Go test
TestSharedMutationCasesAreRejected from the private schemas and the valid
fixtures: values outside an enum, strings one character over maxLength, an
unknown member and a duplicate key, which every side must reject, and strings
one UTF-8 byte over a byte bound, on whose verdict every side must agree. Here
the Python schema validator and decode_private check the same cases, so a
mutation accepted by one side only fails a test.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from private_schemas import private_validator
from test_contracts import GO_ONLY_TYPES, INDEX, MODELS

from contractor_runtime.contracts import PrivateProtocolDecodeError, decode_private

FIXTURES = Path(__file__).parents[2] / "api" / "testdata" / "v1alpha1"
CASES = json.loads((FIXTURES / "mutation-cases.json").read_text(encoding="utf-8"))
UNKNOWN_MEMBER = "contractorUnknownMember"
SENTINELS = CASES["enumSentinels"]


def _tokens(pointer: str) -> list[str]:
    return [token.replace("~1", "/").replace("~0", "~") for token in pointer.split("/")[1:]]


def _escape(token: str) -> str:
    return token.replace("~", "~0").replace("/", "~1")


def _value_at(document: Any, pointer: str) -> Any:
    target = document
    for token in _tokens(pointer):
        target = target[int(token)] if isinstance(target, list) else target[token]
    return target


def _set_value(document: Any, pointer: str, value: Any) -> Any:
    tokens = _tokens(pointer)
    if not tokens:
        return value
    parent = _value_at(document, "".join("/" + _escape(token) for token in tokens[:-1]))
    if isinstance(parent, list):
        parent[int(tokens[-1])] = value
    else:
        parent[tokens[-1]] = value
    return document


def _encode(value: Any, pointer: str, duplicate: str | None) -> str:
    """Compact JSON with members in key order; the object at duplicate repeats its first."""

    if isinstance(value, dict):
        keys = sorted(value)
        if pointer == duplicate and keys:
            keys = [keys[0], *keys]
        members = (
            json.dumps(key, ensure_ascii=False)
            + ":"
            + _encode(value[key], f"{pointer}/{_escape(key)}", duplicate)
            for key in keys
        )
        return "{" + ",".join(members) + "}"
    if isinstance(value, list):
        items = (_encode(item, f"{pointer}/{index}", duplicate) for index, item in enumerate(value))
        return "[" + ",".join(items) + "]"
    return json.dumps(value, ensure_ascii=False)


def _mutation(raw: str, kind: str, pointer: str, bound: int = 0) -> str:
    """The fixture with one mutation applied, as the Go generator builds it."""

    document = json.loads(raw)
    duplicate = None
    if kind == "enum":
        current = _value_at(document, pointer)
        number = isinstance(current, int | float) and not isinstance(current, bool)
        document = _set_value(document, pointer, SENTINELS["number" if number else "string"])
    elif kind == "maxLength":
        document = _set_value(document, pointer, "a" * (bound + 1))
    elif kind == "maxBytes":
        document = _set_value(document, pointer, "a" * (bound - 1) + "é")
    elif kind == "unknownMember":
        _value_at(document, pointer)[UNKNOWN_MEMBER] = True
    elif kind == "duplicateKey":
        duplicate = pointer
    else:
        raise ValueError(f"unknown mutation {kind}")
    return _encode(document, "", duplicate)


def _decoder_rejects(model: Any, document: str) -> bool:
    try:
        decode_private(model, document.encode("utf-8"))
    except PrivateProtocolDecodeError:
        return True
    return False


def test_shared_mutation_cases_are_rejected() -> None:
    assert CASES["cases"].keys() == INDEX["valid"].keys()
    problems: list[str] = []
    tested = 0
    for name, cases in sorted(CASES["cases"].items()):
        entry = INDEX["valid"][name]
        raw = (FIXTURES / "valid" / name).read_text(encoding="utf-8")
        validator = private_validator(entry["schema"])
        model = None if entry["type"] in GO_ONLY_TYPES else MODELS[entry["type"]]
        mutations = [
            *(("enum", pointer, 0) for pointer in cases["enum"]),
            *(("maxLength", item["pointer"], item["maxLength"]) for item in cases["maxLength"]),
            *(("unknownMember", pointer, 0) for pointer in cases["unknownMember"]),
            *(("duplicateKey", pointer, 0) for pointer in cases["duplicateKey"]),
        ]
        for kind, pointer, bound in mutations:
            tested += 1
            document = _mutation(raw, kind, pointer, bound)
            # A JSON parser keeps one of two equal keys, so a schema cannot see them.
            if kind != "duplicateKey" and not any(validator.iter_errors(json.loads(document))):
                problems.append(f"{name} {kind} {pointer}: the schema accepts it")
            if model is not None and not _decoder_rejects(model, document):
                problems.append(f"{name} {kind} {pointer}: decode_private accepts it")
        for item in cases["maxBytes"]:
            tested += 1
            document = _mutation(raw, "maxBytes", item["pointer"], item["maxLength"])
            expected = item["verdict"] == "reject"
            if any(validator.iter_errors(json.loads(document))) is not expected:
                problems.append(f"{name} maxBytes {item['pointer']}: the schema disagrees")
            if model is not None and _decoder_rejects(model, document) is not expected:
                problems.append(f"{name} maxBytes {item['pointer']}: decode_private disagrees")
    assert tested > 0
    assert problems == []
