package public

import "net/http"

func (c contextHandlers) registerOperationsRoutes(mux *http.ServeMux) {
	mux.HandleFunc("GET /v1/operations/credentials", c.credentials.listCredentials)
	mux.HandleFunc("POST /v1/operations/credentials", c.credentials.createCredential)
	mux.HandleFunc("GET /v1/operations/credentials/{credentialId}", c.credentials.getCredential)
	mux.HandleFunc("DELETE /v1/operations/credentials/{credentialId}", c.credentials.deleteCredential)
	mux.HandleFunc("GET /v1/operations/runtime-configs", c.runtimeConfiguration.listRuntimeConfigs)
	mux.HandleFunc("POST /v1/operations/runtime-configs", c.runtimeConfiguration.publishRuntimeConfig)
	mux.HandleFunc("GET /v1/operations/runtime-configs/{name}/versions/{version}", c.runtimeConfiguration.getRuntimeConfig)
	mux.HandleFunc("GET /v1/operations/runtime-labels", c.runtimeConfiguration.listRuntimeLabels)
	mux.HandleFunc("GET /v1/operations/runtime-labels/{label}", c.runtimeConfiguration.getRuntimeLabel)
	mux.HandleFunc("PUT /v1/operations/runtime-labels/{label}", c.runtimeConfiguration.putRuntimeLabel)
	mux.HandleFunc("DELETE /v1/operations/runtime-labels/{label}", c.runtimeConfiguration.deleteRuntimeLabel)
	mux.HandleFunc("GET /v1/operations/runtime-credentials", c.runtimeConfiguration.listRuntimeCredentials)
	mux.HandleFunc("POST /v1/operations/runtime-credentials", c.runtimeConfiguration.createRuntimeCredential)
	mux.HandleFunc("GET /v1/operations/runtime-credentials/{credentialId}", c.runtimeConfiguration.getRuntimeCredential)
	mux.HandleFunc("DELETE /v1/operations/runtime-credentials/{credentialId}", c.runtimeConfiguration.deleteRuntimeCredential)
	mux.HandleFunc("GET /v1/operations/runtime-agent-principals", c.runtimeConfiguration.listRuntimeAgentPrincipals)
	mux.HandleFunc("GET /v1/operations/runtime-agent-principals/{runtimeAgentId}", c.runtimeConfiguration.getRuntimeAgentPrincipal)
	mux.HandleFunc("DELETE /v1/operations/runtime-agent-principals/{runtimeAgentId}", c.runtimeConfiguration.deleteRuntimeAgentPrincipal)
	mux.HandleFunc("PUT /v1/operations/runtime-agent-principals/{runtimeAgentId}/labels", c.runtimeConfiguration.putRuntimeAgentLabels)
	mux.HandleFunc("GET /v1/operations/snapshot", c.operations.getOperationsSnapshot)
	mux.HandleFunc("GET /v1/operations/performance", c.operations.getPerformance)
	mux.HandleFunc("GET /v1/operations/performance/history", c.operations.getPerformanceHistory)
	mux.HandleFunc("GET /v1/operations/allocation-history", c.operations.listAllocationResourceHistory)
	mux.HandleFunc("GET /v1/operations/runtime-agents", c.operations.listRuntimeAgents)
	mux.HandleFunc("GET /v1/operations/allocations", c.operations.listAllocations)
	mux.HandleFunc("GET /v1/operations/settings/scheduler", c.operations.getSchedulerSettings)
	mux.HandleFunc("PUT /v1/operations/settings/scheduler", c.operations.putSchedulerSettings)
	mux.HandleFunc("/v1/operations/credentials/{credentialId}", methodNotAllowed)
	mux.HandleFunc("/v1/operations/credentials", methodNotAllowed)
	mux.HandleFunc("/v1/operations/runtime-configs/{name}/versions/{version}", methodNotAllowed)
	mux.HandleFunc("/v1/operations/runtime-configs", methodNotAllowed)
	mux.HandleFunc("/v1/operations/runtime-labels/{label}", methodNotAllowed)
	mux.HandleFunc("/v1/operations/runtime-labels", methodNotAllowed)
	mux.HandleFunc("/v1/operations/runtime-credentials/{credentialId}", methodNotAllowed)
	mux.HandleFunc("/v1/operations/runtime-credentials", methodNotAllowed)
	mux.HandleFunc("/v1/operations/snapshot", methodNotAllowed)
	mux.HandleFunc("/v1/operations/performance", methodNotAllowed)
	mux.HandleFunc("/v1/operations/performance/history", methodNotAllowed)
	mux.HandleFunc("/v1/operations/allocation-history", methodNotAllowed)
	mux.HandleFunc("/v1/operations/runtime-agents", methodNotAllowed)
	mux.HandleFunc("/v1/operations/allocations", methodNotAllowed)
	mux.HandleFunc("/v1/operations/settings/scheduler", methodNotAllowed)
}
