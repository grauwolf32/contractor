package public

import "net/http"

func (c contextHandlers) registerRunRoutes(mux *http.ServeMux) {
	c.artifacts.registerArchiveRoutes(mux, "/v1/runs/{runID}/artifacts/{namespace}/{name}", c.artifacts.runArchiveStore)
	mux.HandleFunc("POST /v1/runs", c.runs.createRun)
	mux.HandleFunc("GET /v1/runs", c.runs.listRuns)
	mux.HandleFunc("POST /v1/runs/{runID}/cancel", c.runs.cancelRun)
	mux.HandleFunc("POST /v1/runs/{runID}/resume", c.runs.resumeRun)
	mux.HandleFunc("POST /v1/runs/{runID}/retry-gateway", c.runs.retryRunGateway)
	mux.HandleFunc("/v1/runs/{runID}/retry-gateway", methodNotAllowed)
	mux.HandleFunc("DELETE /v1/runs/{runID}", c.runs.deleteRun)
	mux.HandleFunc("GET /v1/runs/{runID}", c.runs.getRun)
	mux.HandleFunc("GET /v1/runs/{runID}/repeat-draft", c.runRepeat.getRunRepeatDraft)
	mux.HandleFunc("GET /v1/runs/{runID}/outputs/{slot}", c.artifacts.getRunOutput)
	mux.HandleFunc("GET /v1/runs/{runID}/artifacts", c.artifacts.listRunArtifacts)
	mux.HandleFunc("GET /v1/runs/{runID}/finding-proposals", c.findings.listRunFindingProposals)
	mux.HandleFunc("GET /v1/runs/{runID}/artifacts/{namespace}/{name}", c.artifacts.getRunArtifact)
	mux.HandleFunc("GET /v1/runs/{runID}/artifacts/{namespace}/{name}/metadata", c.artifacts.getRunArtifactMetadata)
	mux.HandleFunc("GET /v1/runs/{runID}/artifacts/{namespace}/{name}/versions", c.artifacts.listRunArtifactVersions)
	mux.HandleFunc("GET /v1/runs/{runID}/artifacts/{namespace}/{name}/lineage", c.artifacts.listRunArtifactLineage)
	mux.HandleFunc("/v1/runs/{runID}/artifacts/{namespace}/{name}/metadata", methodNotAllowed)
	mux.HandleFunc("/v1/runs/{runID}/artifacts/{namespace}/{name}/versions", methodNotAllowed)
	mux.HandleFunc("/v1/runs/{runID}/artifacts/{namespace}/{name}/lineage", methodNotAllowed)
	mux.HandleFunc("/v1/runs/{runID}/artifacts/{namespace}/{name}", methodNotAllowed)
	mux.HandleFunc("/v1/runs/{runID}/artifacts", methodNotAllowed)
	mux.HandleFunc("/v1/runs/{runID}/finding-proposals", methodNotAllowed)
	mux.HandleFunc("/v1/runs/{runID}/outputs/{slot}", methodNotAllowed)
	mux.HandleFunc("/v1/runs/{runID}/cancel", methodNotAllowed)
	mux.HandleFunc("/v1/runs/{runID}/resume", methodNotAllowed)
	mux.HandleFunc("/v1/runs/{runID}/repeat-draft", methodNotAllowed)
	mux.HandleFunc("/v1/runs/{runID}", methodNotAllowed)
	mux.HandleFunc("/v1/runs", methodNotAllowed)
}
