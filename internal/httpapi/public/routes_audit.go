package public

import "net/http"

func (c contextHandlers) registerAuditRoutes(mux *http.ServeMux) {
	mux.HandleFunc("GET /v1/audits", c.audits.listProjectAudits)
	mux.HandleFunc("GET /v1/findings", c.audits.listOwnerFindings)
	mux.HandleFunc("GET /v1/reviews", c.audits.listOwnerReviews)
	mux.HandleFunc("/v1/audits", methodNotAllowed)
	mux.HandleFunc("/v1/findings", methodNotAllowed)
	mux.HandleFunc("/v1/reviews", methodNotAllowed)
	mux.HandleFunc("GET /v1/audit-profiles", c.audits.listAuditProfiles)
	mux.HandleFunc("GET /v1/audit-profiles/{name}/versions/{version}", c.audits.getAuditProfile)
	mux.HandleFunc("GET /v1/audit-standards", c.audits.listAuditStandards)
	mux.HandleFunc("GET /v1/audit-standards/{scheme}/versions/{version}", c.audits.getAuditStandard)
	mux.HandleFunc("POST /v1/projects/{projectId}/audits", c.audits.createAudit)
	mux.HandleFunc("GET /v1/projects/{projectId}/audits", c.audits.listProjectAudits)
	mux.HandleFunc("GET /v1/audits/{auditId}", c.audits.getAudit)
	mux.HandleFunc("GET /v1/audits/{auditId}/events", c.audits.listAuditEvents)
	mux.HandleFunc("POST /v1/audits/{auditId}/start", c.audits.startAudit)
	mux.HandleFunc("POST /v1/audits/{auditId}/pause", c.audits.pauseAudit)
	mux.HandleFunc("POST /v1/audits/{auditId}/resume", c.audits.resumeAudit)
	mux.HandleFunc("POST /v1/audits/{auditId}/cancel", c.audits.cancelAudit)
	mux.HandleFunc("DELETE /v1/audits/{auditId}", c.audits.deleteAudit)
	mux.HandleFunc("GET /v1/audits/{auditId}/items", c.audits.listAuditItems)
	mux.HandleFunc("GET /v1/audits/{auditId}/coverage", c.audits.listAuditCoverage)
	mux.HandleFunc("GET /v1/audits/{auditId}/workspace", c.audits.getAuditWorkspace)
	mux.HandleFunc("GET /v1/audits/{auditId}/reviews/{requestId}", c.audits.getAuditReview)
	mux.HandleFunc("GET /v1/audits/{auditId}/report", c.audits.getAuditReport)
	mux.HandleFunc("GET /v1/audits/{auditId}/finding-proposals", c.findings.listAuditFindingProposals)
	mux.HandleFunc("POST /v1/audits/{auditId}/finding-proposal-imports", c.findings.importAuditFindingProposal)
	mux.HandleFunc("POST /v1/finding-collections", c.findings.publishFindingCollection)
	mux.HandleFunc("GET /v1/audits/{auditId}/findings", c.audits.listAuditFindings)
	mux.HandleFunc("GET /v1/audits/{auditId}/findings/{findingId}", c.audits.getAuditFinding)
	mux.HandleFunc("GET /v1/audits/{auditId}/findings/{findingId}/provenance", c.audits.listAuditFindingProvenance)
	mux.HandleFunc("POST /v1/audits/{auditId}/findings/{findingId}/reviews", c.audits.createAuditFindingReview)
	mux.HandleFunc("GET /v1/audits/{auditId}/reviews", c.audits.listAuditReviews)
	mux.HandleFunc("POST /v1/audits/{auditId}/reviews/{requestId}/decisions", c.audits.decideAuditReview)
	mux.HandleFunc("/v1/audit-profiles/{name}/versions/{version}", methodNotAllowed)
	mux.HandleFunc("/v1/audit-profiles", methodNotAllowed)
	mux.HandleFunc("/v1/projects/{projectId}/audits", methodNotAllowed)
	mux.HandleFunc("/v1/audits/{auditId}/start", methodNotAllowed)
	mux.HandleFunc("/v1/audits/{auditId}/events", methodNotAllowed)
	mux.HandleFunc("/v1/audits/{auditId}/items", methodNotAllowed)
	mux.HandleFunc("/v1/audits/{auditId}/coverage", methodNotAllowed)
	mux.HandleFunc("/v1/audits/{auditId}/workspace", methodNotAllowed)
	mux.HandleFunc("/v1/audits/{auditId}/reviews/{requestId}", methodNotAllowed)
	mux.HandleFunc("/v1/audits/{auditId}/report", methodNotAllowed)
	mux.HandleFunc("/v1/audits/{auditId}/finding-proposals", methodNotAllowed)
	mux.HandleFunc("/v1/audits/{auditId}/finding-proposal-imports", methodNotAllowed)
	mux.HandleFunc("/v1/finding-collections", methodNotAllowed)
	mux.HandleFunc("/v1/audits/{auditId}/findings/{findingId}/provenance", methodNotAllowed)
	mux.HandleFunc("/v1/audits/{auditId}/findings/{findingId}/reviews", methodNotAllowed)
	mux.HandleFunc("/v1/audits/{auditId}/findings/{findingId}", methodNotAllowed)
	mux.HandleFunc("/v1/audits/{auditId}/findings", methodNotAllowed)
	mux.HandleFunc("/v1/audits/{auditId}/reviews/{requestId}/decisions", methodNotAllowed)
	mux.HandleFunc("/v1/audits/{auditId}/reviews", methodNotAllowed)
	mux.HandleFunc("/v1/audits/{auditId}", methodNotAllowed)
}
