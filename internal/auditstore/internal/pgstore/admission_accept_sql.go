package pgstore

var preparedRoundEvents = auditEvents(auditEvent("'round.accepted'", "$3::text", "1",
	`jsonb_build_object('round',$11::integer,'items',$8::integer,'reviews',(SELECT prepared_review_count FROM audit_rounds WHERE audit_id=$1 AND round_id=$3))`))

// acceptPreparedRoundSQL checks constant-size parent seals. Child rows were
// inserted and proved in bounded pages; deletion counters prevent a stale seal.
var acceptPreparedRoundSQL = `
WITH project_gate AS MATERIALIZED (
 SELECT contractor_require_active_audit_project(project_id,owner_id) FROM audits WHERE audit_id=$1
), parents AS MATERIALIZED (
 SELECT audit.audit_id FROM audits AS audit
 JOIN audit_rounds AS previous ON previous.audit_id=audit.audit_id AND previous.round_id=$2
 JOIN audit_rounds AS proposed ON proposed.audit_id=audit.audit_id AND proposed.round_id=$3
 CROSS JOIN project_gate
 WHERE audit.audit_id=$1 AND audit.revision=$4 AND audit.state='active' AND audit.dispatch_state='open'
 AND audit.current_round_id=$2 AND previous.state='closed' AND proposed.state='proposed'
 AND proposed.ordinal=$11 AND proposed.ordinal=previous.ordinal+1 AND proposed.ordinal<=audit.max_rounds
 AND proposed.prepared_generation=$5 AND proposed.prepared_page_count=$9 AND proposed.prepared_pages_digest=$10
 AND proposed.prepared_staged_count=$8 AND proposed.expected_item_count=$8 AND $8>0
 AND proposed.manifest_ref=$6::jsonb AND proposed.manifest_digest=$7 AND proposed.acceptance_digest=$7
 AND previous.admission_checkpoint->>'generation'=$5
 AND (previous.admission_checkpoint->>'deadline_at')::timestamptz>clock_timestamp()
 AND (audit.deadline_at IS NULL OR audit.deadline_at>clock_timestamp())
 AND $8<=audit.max_items_per_round
 AND (SELECT COALESCE(sum(expected_item_count),0) FROM audit_rounds WHERE audit_id=$1 AND state<>'proposed')+$8<=audit.max_items_total
 FOR UPDATE OF audit,previous,proposed
), accepted AS (
 UPDATE audit_rounds SET state='accepted',revision=revision+1,updated_at=clock_timestamp()
 FROM parents WHERE audit_rounds.audit_id=parents.audit_id AND audit_rounds.round_id=$3 RETURNING audit_rounds.*
), advanced AS (
 UPDATE audits AS audit SET current_round_id=$3,` + preparedRoundEvents.advance() + `,updated_at=clock_timestamp()
 FROM accepted WHERE audit.audit_id=accepted.audit_id
 RETURNING audit.audit_id,` + preparedRoundEvents.appended() + `
)
SELECT ` + prefixedRoundColumns("accepted") + ` FROM accepted CROSS JOIN advanced`

// Generated byte/related counts and the private seal are selected before
// prepared_execution is hydrated. Caller-selected IDs are at most one batch.
const selectedPreparedHeadersSQL = `
SELECT item.item_id,item.ordinal,item.prepared_projection_bytes,item.prepared_related_count
FROM unnest($3::text[]) WITH ORDINALITY AS selected(id,position)
JOIN audit_items AS item ON item.item_id=selected.id AND item.audit_id=$1 AND item.round_id=$2
JOIN audit_rounds AS round USING(audit_id,round_id)
WHERE round.state<>'proposed' AND round.prepared_generation IS NOT NULL
 AND round.prepared_staged_count=round.expected_item_count
 AND item.prepared_execution IS NOT NULL AND item.prepared_page_ordinal<round.prepared_page_count
ORDER BY selected.position`

const selectedPreparedItemsSQL = `
SELECT item.prepared_execution,item.ordinal
FROM unnest($3::text[]) WITH ORDINALITY AS selected(id,position)
JOIN audit_items AS item ON item.item_id=selected.id AND item.audit_id=$1 AND item.round_id=$2
JOIN audit_rounds AS round USING(audit_id,round_id)
WHERE round.state<>'proposed' AND round.prepared_generation IS NOT NULL
 AND round.prepared_staged_count=round.expected_item_count
 AND item.prepared_execution IS NOT NULL AND item.prepared_page_ordinal<round.prepared_page_count
ORDER BY selected.position`
